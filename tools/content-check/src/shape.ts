type SchemaNode = Record<string, any>;

// The keywords the generator understands (contracts/site-data-rules.md).
// Validation-only keywords and annotations don't change a type.
const SUPPORTED = new Set([
  '$schema',
  '$id',
  'title',
  'description',
  '$comment',
  'default',
  'examples',
  'type',
  'properties',
  'required',
  'additionalProperties',
  'items',
  'enum',
  'const',
  'definitions',
  '$ref',
  'minLength',
  'maxLength',
  'pattern',
  'format',
  'minimum',
  'maximum',
  'minItems',
  'maxItems',
  'uniqueItems',
  'x-cv-reference',
]);

const PRIMITIVES: Record<string, string> = { string: 'string', number: 'number', integer: 'number', boolean: 'boolean', null: 'null' };

const HEADER =
  '// Generated by npm run content-shape from @jsonresume/schema 1.3.1 (schema.json) and packages/content/schemas/site.schema.json. Do not edit.';

function isNode(value: unknown): value is SchemaNode {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function unsupported(keyword: string, at: string, reason?: string): Error {
  return new Error(`unsupported keyword "${keyword}" at ${at}${reason === undefined ? '' : `: ${reason}`}`);
}

// `featuredProjects` → `FeaturedProjects`, `first-name` → `FirstName`.
function pascal(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter((part) => part !== '')
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('');
}

// The singular used for array items: one final `s` dropped.
function singular(name: string): string {
  return name.endsWith('s') ? name.slice(0, -1) : name;
}

// `$schema` and other names that aren't plain identifiers go in quotes.
function propertyName(name: string): string {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : `'${name.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function literal(value: unknown): string {
  return typeof value === 'string' ? `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'` : JSON.stringify(value);
}

// A one-line JSDoc comment. Newlines are written as `\n` and `*/` can't end it.
function jsdoc(indent: string, description: unknown): string[] {
  if (typeof description !== 'string') return [];
  return [`${indent}/** ${description.replace(/\n/g, '\\n').replace(/\*\//g, '*\\/')} */`];
}

// Every keyword in the schema must be one the generator understands.
function checkKeywords(node: unknown, at: string): void {
  if (!isNode(node)) return;
  for (const key of Object.keys(node)) if (!SUPPORTED.has(key)) throw unsupported(key, at);
  for (const key of ['properties', 'definitions']) {
    if (isNode(node[key])) for (const [name, child] of Object.entries(node[key])) checkKeywords(child, `${at}/${key}/${name}`);
  }
  for (const key of ['items', 'additionalProperties']) checkKeywords(node[key], `${at}/${key}`);
}

// One root's interfaces (`Resume` or `SiteData`), depth-first in property
// order. `names` is shared, so a name used for two different schemas stops the
// generator.
function generateRoot(rootName: string, root: SchemaNode, names: Map<string, SchemaNode>): string[] {
  checkKeywords(root, '#');
  const blocks: string[] = [];

  const resolve = (node: SchemaNode, at: string): { node: SchemaNode; at: string } => {
    if (typeof node.$ref !== 'string') return { node, at };
    const name = /^#\/definitions\/(.+)$/.exec(node.$ref)?.[1];
    const target = name === undefined ? undefined : root.definitions?.[name];
    if (!isNode(target)) throw unsupported('$ref', at, `${JSON.stringify(node.$ref)} is not a definition`);
    return { node: target, at: `#/definitions/${name}` };
  };

  // The TypeScript type of a schema. An object is named `name.object`, and an
  // array's items `name.item`, made from the property: `profiles` →
  // `ResumeProfile`.
  const typeOf = (original: SchemaNode, originalAt: string, name: { object: string; item: string }, after: (() => void)[]): string => {
    const { node, at } = resolve(original, originalAt);
    if (Array.isArray(node.enum)) return node.enum.map(literal).join(' | ');
    if (Object.hasOwn(node, 'const')) return literal(node.const);
    if (Array.isArray(node.type)) throw unsupported('type', at, 'a list of types');
    if (typeof node.type !== 'string') throw unsupported('type', at, 'a type is required');
    if (Object.hasOwn(PRIMITIVES, node.type)) return PRIMITIVES[node.type]!;
    if (node.type === 'array') {
      if (!isNode(node.items)) throw unsupported('items', at, 'an array needs one schema for its items');
      const item = typeOf(node.items, `${at}/items`, { object: name.item, item: name.item }, after);
      return /[ |]/.test(item) ? `(${item})[]` : `${item}[]`;
    }
    if (node.type === 'object') {
      if (isNode(node.properties)) {
        const seen = names.get(name.object);
        if (seen !== undefined && seen !== node) throw new Error(`the type name ${name.object} is used for two schemas, at ${at}`);
        if (seen === undefined) {
          names.set(name.object, node);
          after.push(() => emitInterface(name.object, node, at));
        }
        return name.object;
      }
      if (isNode(node.additionalProperties)) {
        const value = `${name.object}Value`;
        return `Record<string, ${typeOf(node.additionalProperties, `${at}/additionalProperties`, { object: value, item: value }, after)}>`;
      }
      throw unsupported('type', at, 'an object needs properties or additionalProperties');
    }
    throw unsupported('type', at, `unknown type ${JSON.stringify(node.type)}`);
  };

  const emitInterface = (name: string, node: SchemaNode, at: string): void => {
    const required: unknown[] = Array.isArray(node.required) ? node.required : [];
    const lines = [...jsdoc('', node.description), `export interface ${name} {`];
    const after: (() => void)[] = [];
    for (const [key, child] of Object.entries(node.properties as Record<string, SchemaNode>)) {
      if (!isNode(child)) throw unsupported('properties', `${at}/properties/${key}`, 'not a schema');
      const childAt = `${at}/properties/${key}`;
      const type = typeOf(child, childAt, { object: `${rootName}${pascal(key)}`, item: `${rootName}${pascal(singular(key))}` }, after);
      const description = child.description ?? (typeof child.$ref === 'string' ? resolve(child, childAt).node.description : undefined);
      lines.push(...jsdoc('  ', description), `  ${propertyName(key)}${required.includes(key) ? '' : '?'}: ${type};`);
    }
    lines.push('}');
    blocks.push(lines.join('\n'));
    for (const emit of after) emit();
  };

  if (root.type !== 'object' || !isNode(root.properties)) throw unsupported('type', '#', 'the root must be an object with properties');
  names.set(rootName, root);
  emitInterface(rootName, root, '#');
  return blocks;
}

// TypeScript for both derived schemas (research R10,
// contracts/content-package.md Generated file). Deterministic: no timestamps.
export function generateShape(schemas: { resume: object; site: object }): string {
  const names = new Map<string, SchemaNode>();
  const blocks = [
    ...generateRoot('Resume', schemas.resume as SchemaNode, names),
    ...generateRoot('SiteData', schemas.site as SchemaNode, names),
  ];
  return `${HEADER}\n\n${blocks.join('\n\n')}\n`;
}
