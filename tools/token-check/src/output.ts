import { compare } from '../../traceability/src/report.ts';
import { GENERIC_FAMILIES } from './classify.ts';
import { TYPOGRAPHY_PARTS, codeName, isBreakpoint } from './names.ts';
import { EXPORT_FILE, MOTION_FILE } from './paths.ts';
import { combinationName } from './themes.ts';
import type { Groups } from './themes.ts';
import { fontFamilyList, parseFontWeight } from './values.ts';

export type OutputInput = {
  // Every full combination, each with its resolved tokens.
  combinations: { name: string; tokens: Map<string, { type: string; value: unknown }> }[];
  // The description: every name and its type.
  types: Map<string, string>;
  groups: Groups;
  // The active theme of every group.
  active: Map<string, string>;
};

// A typography token's CSS texts, by part. A part the token doesn't set is
// left out.
type CssText = string | Record<string, string>;

const CSS_HEADER = `/* Generated by npm run token-output from ${EXPORT_FILE} and\n   ${MOTION_FILE}. Do not edit. */\n`;

const TS_HEADER = `// Generated by npm run token-output from ${EXPORT_FILE} and ${MOTION_FILE}. Do not edit.\n`;

const UNITLESS = /^\s*-?(?:\d+\.?\d*|\.\d+)\s*$/;

const text = (value: unknown) => String(value).trim();

// A unitless length means pixels.
function length(value: unknown): string {
  return UNITLESS.test(text(value)) ? `${text(value)}px` : text(value);
}

function hexChannels(hex: string): number[] {
  const digits = hex.slice(1);
  const full = digits.length <= 4 ? [...digits].map((digit) => digit + digit).join('') : digits;
  return [0, 2, 4].map((start) => Number.parseInt(full.slice(start, start + 2), 16));
}

function color(value: unknown): string {
  const rgba = /^rgba\(\s*(#[0-9a-f]+)\s*,\s*([^)]*?)\s*\)$/i.exec(text(value));
  if (rgba === null) return text(value);
  const [red, green, blue] = hexChannels(rgba[1]!);
  return `rgb(${red} ${green} ${blue} / ${rgba[2]})`;
}

function fontFamilies(value: unknown): string {
  return (fontFamilyList(value) ?? [])
    .map((family) => (GENERIC_FAMILIES.includes(family.toLowerCase()) ? family : JSON.stringify(family)))
    .join(', ');
}

function textDecoration(value: unknown): string {
  const keyword = text(value).toLowerCase();
  return keyword === 'strike-through' ? 'line-through' : keyword;
}

function typography(value: Record<string, unknown>): Record<string, string> {
  const parts: Record<string, string> = {};
  if ('fontFamilies' in value) parts['font-family'] = fontFamilies(value.fontFamilies);
  if ('fontSizes' in value) parts['font-size'] = length(value.fontSizes);
  if ('fontWeights' in value) {
    const weight = parseFontWeight(value.fontWeights)!;
    parts['font-weight'] = weight.weight;
    if (weight.italic) parts['font-style'] = 'italic';
  }
  if ('lineHeights' in value) parts['line-height'] = text(value.lineHeights);
  if ('letterSpacing' in value) parts['letter-spacing'] = length(value.letterSpacing);
  if ('textCase' in value) parts['text-transform'] = text(value.textCase).toLowerCase();
  if ('textDecoration' in value) parts['text-decoration'] = textDecoration(value.textDecoration);
  return parts;
}

function shadow(value: unknown): string {
  return (value as Record<string, unknown>[])
    .map((item) => {
      const parts = [item.offsetX, item.offsetY, item.blur, item.spread].map(length);
      return `${item.inset === true ? 'inset ' : ''}${parts.join(' ')} ${color(item.color)}`;
    })
    .join(', ');
}

// A resolved value written as CSS (contracts/token-output.md, Values).
export function cssText(type: string, value: unknown): CssText {
  switch (type) {
    case 'color':
      return color(value);
    case 'dimension':
    case 'spacing':
    case 'sizing':
    case 'borderRadius':
    case 'borderWidth':
    case 'fontSizes':
    case 'letterSpacing':
      return length(value);
    case 'rotation':
      return UNITLESS.test(text(value)) ? `${text(value)}deg` : text(value);
    case 'fontFamilies':
      return fontFamilies(value);
    case 'fontWeights':
      return parseFontWeight(value)!.weight;
    case 'textCase':
      return text(value).toLowerCase();
    case 'textDecoration':
      return textDecoration(value);
    case 'typography':
      return typography(value as Record<string, unknown>);
    case 'shadow':
      return shadow(value);
    case 'cubicBezier':
      return `cubic-bezier(${(value as number[]).join(', ')})`;
    default:
      return text(value);
  }
}

function sorted<T>(entries: Iterable<[string, T]>): [string, T][] {
  return [...entries].sort(([a], [b]) => compare(a, b));
}

// TypeScript source for a value: keys and strings with JSON.stringify, two
// spaces per level, keys in code-unit order.
function literal(value: unknown, indent: string): string {
  if (typeof value === 'string') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map((item) => literal(item, indent)).join(', ')}]`;
  const entries = sorted(value instanceof Map ? value : Object.entries(value as object));
  if (entries.length === 0) return '{}';
  const inner = `${indent}  `;
  return `{\n${entries.map(([key, item]) => `${inner}${JSON.stringify(key)}: ${literal(item, inner)}`).join(',\n')}\n${indent}}`;
}

// The derived output: the CSS file and the TS file (research R10, R11;
// contracts/token-output.md). Nothing in either tells which source a token
// came from (FR-025, FR-049).
export function buildOutput(input: OutputInput): { css: string; ts: string } {
  const activeName = combinationName(sorted(input.active));
  const values = new Map(
    input.combinations.map(({ name, tokens }) => [
      name,
      new Map(sorted([...tokens].map(([token, { type, value }]) => [token, cssText(type, value)]))),
    ]),
  );

  const active = values.get(activeName) ?? new Map<string, CssText>();
  const properties: [string, string][] = [];
  for (const [name, value] of active) {
    if (typeof value === 'string') properties.push([codeName(name), value]);
    else for (const part of TYPOGRAPHY_PARTS) if (part in value) properties.push([codeName(`${name}.${part}`), value[part]!]);
  }
  const breakpoints = [...active].filter(([name]) => isBreakpoint(name));
  let css = `${CSS_HEADER}:root {\n${sorted(properties)
    .map(([name, value]) => `  ${name}: ${value};\n`)
    .join('')}}\n`;
  if (breakpoints.length > 0) {
    css += `\n${breakpoints
      .map(([name, value]) => [codeName(name), value] as [string, CssText])
      .sort(([a], [b]) => compare(a, b))
      .map(([name, value]) => `@custom-media ${name} (width >= ${value as string});\n`)
      .join('')}`;
  }

  const declarations = [
    ['tokenTypes', input.types],
    ['themeGroups', input.groups],
    ['activeThemes', input.active],
    ['themeValues', values],
  ] as const;
  const ts = `${TS_HEADER}\n${declarations.map(([name, value]) => `export const ${name} = ${literal(value, '')} as const;\n`).join('\n')}`;
  return { css, ts };
}
